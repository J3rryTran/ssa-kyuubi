{% macro kyuubi_py_write_table(compiled_code, target_relation) %}
{#
  dbt-core injects SQL ephemeral dependencies by prepending a WITH clause to
  compiled_code. That behavior is valid for a SQL consumer but makes a Python
  model syntactically invalid. Preserve the injected CTEs as a Spark SQL query
  and submit only the original Python portion to the Python worker.
#}
{% set extra_cte_sql = [] %}
{% for cte in model.get('extra_ctes', []) %}
  {% do extra_cte_sql.append(cte['sql']) %}
{% endfor %}
{% set python_code = compiled_code %}
{% set ephemeral_query = '' %}
{% if extra_cte_sql | length > 0 %}
  {% set ephemeral_query = 'with' ~ (extra_cte_sql | join(', ')) %}
  {% set injected_prefix = ephemeral_query ~ ' ' %}
  {% if not python_code.startswith(injected_prefix) %}
    {{ exceptions.raise_compiler_error(
      'Kyuubi could not separate SQL ephemeral CTEs from the compiled Python model') }}
  {% endif %}
  {% set python_code = python_code | replace(injected_prefix, '', 1) %}
{% endif %}
{{ python_code }}
# --- Autogenerated dbt materialization code. --- #
kyuubi_ephemeral_query = {{ tojson(ephemeral_query) }}
kyuubi_ephemeral_dataframes = {}

def kyuubi_load_dataframe(relation):
  if relation.startswith("__dbt__cte__") and kyuubi_ephemeral_query:
    if relation not in kyuubi_ephemeral_dataframes:
      quoted_relation = "`{}`".format(relation.replace("`", "``"))
      kyuubi_ephemeral_dataframes[relation] = spark.sql(
        kyuubi_ephemeral_query + "\nSELECT * FROM " + quoted_relation
      )
    return kyuubi_ephemeral_dataframes[relation]
  if relation.lstrip().startswith("("):
    return spark.sql("SELECT * FROM " + relation)
  return spark.table(relation)

dbt = dbtObj(kyuubi_load_dataframe)
df = model(dbt, spark)

import pyspark
try:
  import pandas
  pandas_available = True
except ImportError:
  pandas_available = False

try:
  import pyspark.pandas
  pyspark_pandas_api_available = True
except ImportError:
  pyspark_pandas_api_available = False

try:
  import databricks.koalas
  koalas_available = True
except ImportError:
  koalas_available = False

if pyspark_pandas_api_available and pandas_available and isinstance(df, pandas.core.frame.DataFrame):
  df = pyspark.pandas.frame.DataFrame(df)
elif koalas_available and pandas_available and isinstance(df, pandas.core.frame.DataFrame):
  df = databricks.koalas.frame.DataFrame(df)

if isinstance(df, pyspark.sql.dataframe.DataFrame):
  pass
elif pyspark_pandas_api_available and isinstance(df, pyspark.pandas.frame.DataFrame):
  df = df.to_spark()
elif koalas_available and isinstance(df, databricks.koalas.frame.DataFrame):
  df = df.to_spark()
elif pandas_available and isinstance(df, pandas.core.frame.DataFrame):
  df = spark.createDataFrame(df)
else:
  msg = f"{type(df)} is not a supported type for dbt Python materialization"
  raise Exception(msg)

{% if config.get('materialized') == 'incremental'
    and config.get('incremental_strategy') == 'merge' %}
{% set unique_key = config.get('unique_key') %}
{% if unique_key is string %}
{% set unique_keys = [unique_key] %}
{% else %}
{% set unique_keys = unique_key %}
{% endif %}
from pyspark.sql import functions as kyuubi_functions

kyuubi_unique_keys = {{ tojson(unique_keys) }}
kyuubi_missing_unique_keys = [
  key for key in kyuubi_unique_keys if key not in df.columns
]
if kyuubi_missing_unique_keys:
  raise ValueError(
    "Kyuubi incremental unique_key columns are missing: "
    + ", ".join(kyuubi_missing_unique_keys)
  )

kyuubi_null_key_condition = kyuubi_functions.lit(False)
for kyuubi_key in kyuubi_unique_keys:
  kyuubi_null_key_condition = (
    kyuubi_null_key_condition | df[kyuubi_key].isNull()
  )
if df.filter(kyuubi_null_key_condition).limit(1).count() > 0:
  raise ValueError("Kyuubi incremental unique_key columns contain null values")

kyuubi_duplicate_keys = (
  df.groupBy(*[df[key] for key in kyuubi_unique_keys])
    .agg(kyuubi_functions.count(kyuubi_functions.lit(1)).alias("__kyuubi_count"))
    .filter(kyuubi_functions.col("__kyuubi_count") > 1)
    .limit(1)
    .count()
)
if kyuubi_duplicate_keys > 0:
  raise ValueError("Kyuubi incremental source contains duplicate unique_key values")
{% endif %}

{% set file_format = config.get('file_format') or 'iceberg' %}
kyuubi_writer = (
  df.write.mode("overwrite")
    .format("{{ file_format }}")
    .option("overwriteSchema", "true")
)
{% set partition_by = config.get('partition_by') %}
{% if partition_by %}
{% if partition_by is string %}
{% set partition_columns = [partition_by] %}
{% else %}
{% set partition_columns = partition_by %}
{% endif %}
kyuubi_writer = kyuubi_writer.partitionBy(*{{ tojson(partition_columns) }})
{% endif %}
kyuubi_writer.saveAsTable("{{ target_relation }}")
{%- endmacro %}
